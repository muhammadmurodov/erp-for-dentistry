"""Where the bytes go, and how we know they are still the right bytes.

Four properties this file exists to guarantee, each of which is a way a
document store is normally lost:

1. **A path is never built from user input.** The key is
   `<organization>/<yy>/<mm>/<document id>` — three identifiers this system
   generated. An uploaded filename called `../../../etc/passwd` is a label on
   a row; it never reaches the filesystem. `_resolve` re-checks containment
   anyway, because a guarantee that is only argued is a guarantee that breaks
   the first time somebody adds a caller.

2. **Nothing executes what is stored.** Files are written with no extension
   and mode `0o600`, into directories created `0o700`. The API is the only
   way to read one back; no web server is pointed at this directory.

3. **A write either lands whole or does not land.** Bytes go to a temporary
   file in the destination directory and are `fsync`-ed, then renamed into
   place — an atomic operation on POSIX within one filesystem. A process
   killed mid-upload leaves a stray temporary file, never a truncated
   document that still has a database row claiming a checksum.

4. **The checksum is checked on the way out, not only on the way in.** A
   backup nobody has restored is a hope, so `read` verifies and
   `verify_all` walks the whole store. Silent corruption on the disk becomes
   a refused download and a logged event rather than a file that quietly
   stopped being evidence.
"""

from __future__ import annotations

import hashlib
import os
import uuid
from dataclasses import dataclass
from datetime import date
from pathlib import Path

from app.core.config import get_settings
from app.core.errors import NotFound, ValidationFailed
from app.core.logging import get_logger

log = get_logger(__name__)

#: Read in blocks when checksumming an existing file, so verifying a large
#: store does not depend on any single file fitting in memory.
_CHUNK = 1024 * 1024


def sha256_hex(content: bytes) -> str:
    return hashlib.sha256(content).hexdigest()


@dataclass(frozen=True, slots=True)
class StoredBlob:
    storage_key: str
    checksum_sha256: str
    byte_size: int


@dataclass(frozen=True, slots=True)
class VerificationResult:
    """The answer to "is the store still intact?"."""

    checked: int
    intact: int
    corrupted: list[str]
    missing: list[str]

    @property
    def ok(self) -> bool:
        return not self.corrupted and not self.missing


class DocumentStorage:
    """The filesystem behind the document module.

    Constructed with no arguments in production — the root comes from
    settings — and with an explicit root in tests, so a test never writes
    into the configured store.
    """

    def __init__(self, root: Path | str | None = None) -> None:
        settings = get_settings()
        self._root = Path(root or settings.document_storage_path).resolve()

    @property
    def root(self) -> Path:
        return self._root

    def storage_key(self, *, organization_id: uuid.UUID, document_id: uuid.UUID, on: date) -> str:
        """The key for a new document. Every component is machine-generated.

        Dated directories keep any one directory small enough to list, which
        matters the first time somebody has to look at the store by hand.
        """
        return f"{organization_id}/{on:%Y}/{on:%m}/{document_id}"

    def _resolve(self, storage_key: str) -> Path:
        """Absolute path for a key, refusing anything outside the root.

        The key is generated by this class, so this check should never fire.
        It is here because "should never" is the state of every traversal bug
        before it is found.
        """
        candidate = (self._root / storage_key).resolve()
        if candidate != self._root and self._root not in candidate.parents:
            raise ValidationFailed(
                "Refusing a document path outside the storage root",
                details={"storage_key": storage_key},
            )
        return candidate

    def write(self, *, storage_key: str, content: bytes) -> StoredBlob:
        """Store bytes atomically and return what was actually written."""
        if not content:
            raise ValidationFailed("Refusing to store an empty document")

        path = self._resolve(storage_key)
        path.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
        temporary = path.with_name(f".{path.name}.{os.getpid()}.part")

        descriptor = os.open(temporary, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        try:
            with os.fdopen(descriptor, "wb") as handle:
                handle.write(content)
                handle.flush()
                os.fsync(handle.fileno())
            os.replace(temporary, path)
        except BaseException:
            temporary.unlink(missing_ok=True)
            raise

        # Durability of the rename itself: without this, a crash can leave the
        # directory entry unwritten even though the file's data is on disk.
        directory = os.open(path.parent, os.O_DIRECTORY)
        try:
            os.fsync(directory)
        finally:
            os.close(directory)

        return StoredBlob(
            storage_key=storage_key,
            checksum_sha256=sha256_hex(content),
            byte_size=len(content),
        )

    def read(self, *, storage_key: str, expected_checksum: str) -> bytes:
        """Return the bytes, or refuse because they are no longer the bytes."""
        path = self._resolve(storage_key)
        if not path.is_file():
            raise NotFound(
                "The document's file is missing from storage. Restore it from "
                "a backup; the database still holds its checksum.",
                details={"storage_key": storage_key},
            )
        content = path.read_bytes()
        actual = sha256_hex(content)
        if actual != expected_checksum:
            log.error(
                "document.checksum_mismatch",
                storage_key=storage_key,
                expected=expected_checksum,
                actual=actual,
            )
            raise ValidationFailed(
                "This document's contents no longer match the checksum "
                "recorded when it was uploaded. It is not being served. "
                "Restore it from a backup and verify the store.",
                details={"storage_key": storage_key},
            )
        return content

    def checksum_on_disk(self, *, storage_key: str) -> str | None:
        """Checksum the stored file without loading it whole, or None if gone."""
        path = self._resolve(storage_key)
        if not path.is_file():
            return None
        digest = hashlib.sha256()
        with path.open("rb") as handle:
            while chunk := handle.read(_CHUNK):
                digest.update(chunk)
        return digest.hexdigest()

    def verify(self, *, storage_key: str, expected_checksum: str) -> bool:
        return self.checksum_on_disk(storage_key=storage_key) == expected_checksum

    def verify_all(self, expected: dict[str, str]) -> VerificationResult:
        """Check every document the database knows about.

        Takes the mapping rather than reading the database, so the same
        function serves the CLI, the readiness check and a test, and so the
        storage layer keeps knowing nothing about SQLAlchemy.
        """
        corrupted: list[str] = []
        missing: list[str] = []
        for storage_key, checksum in expected.items():
            actual = self.checksum_on_disk(storage_key=storage_key)
            if actual is None:
                missing.append(storage_key)
            elif actual != checksum:
                corrupted.append(storage_key)
        return VerificationResult(
            checked=len(expected),
            intact=len(expected) - len(corrupted) - len(missing),
            corrupted=sorted(corrupted),
            missing=sorted(missing),
        )

    def orphans(self, known_keys: set[str]) -> list[str]:
        """Files on disk that no document row claims.

        A backup restored over a newer database, or an upload whose
        transaction rolled back after the bytes were written. Reported, never
        deleted: this module does not destroy files, and an orphan is
        evidence of something worth understanding.
        """
        found: list[str] = []
        if not self._root.is_dir():
            return found
        for path in self._root.rglob("*"):
            if not path.is_file() or path.name.startswith("."):
                continue
            key = path.relative_to(self._root).as_posix()
            if key not in known_keys:
                found.append(key)
        return sorted(found)
